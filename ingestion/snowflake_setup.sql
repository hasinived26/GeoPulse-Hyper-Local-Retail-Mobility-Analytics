CREATE WAREHOUSE IF NOT EXISTS geopulse_wh
  WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS geopulse;
CREATE SCHEMA IF NOT EXISTS geopulse.raw;

USE WAREHOUSE geopulse_wh;
USE SCHEMA geopulse.raw;

CREATE TABLE IF NOT EXISTS pings_load (
  device_id STRING, lat FLOAT, lon FLOAT, ts_local TIMESTAMP_NTZ
);

CREATE FILE FORMAT IF NOT EXISTS csv_gz TYPE = CSV SKIP_HEADER = 1 COMPRESSION = GZIP;
CREATE STAGE IF NOT EXISTS pings_stage FILE_FORMAT = csv_gz;